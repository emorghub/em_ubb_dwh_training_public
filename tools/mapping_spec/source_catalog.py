"""Gap analysis: what the source systems could deliver, compared with what sql/ holds.

The analysts keep a source systems catalog (an Excel file in business-documents/,
UBB_Source_Systems_Entities_Attributes_v<N>.xlsx): every attribute each source
system has, the staging table ("Interface Dataset") it would arrive in, and
whether today's interface delivers it. This tool reads that catalog and checks
every attribute against the table scripts in sql/ (schema_catalog.py). No
database is involved.

    python tools/mapping_spec/source_catalog.py find PRIORITY
    python tools/mapping_spec/source_catalog.py gaps STG_LOAN_COLLATERAL_REL
    python tools/mapping_spec/source_catalog.py gaps            # the whole catalog

`find` searches attribute names, business names and descriptions. `gaps`
lists every attribute that is not simply "delivered and in sql/", plus the
staging columns in sql/ that the catalog does not mention. Each attribute gets
one status:

  delivered          in the current interface and in the staging table script
  interface_change   the source has it, the staging table exists, the column
                     does not: an interface (delivery agreement) change, then
                     new staging and core columns
  new_interface      the source has it, but no staging table receives it: a new
                     interface, delivery agreement and staging table
  not_staged         the catalog says the interface delivers it, but the staging
                     table does not have it. Allowed: an agreement may deliver
                     columns staging does not load. If a request needs it, the
                     developer adds the column (dev-1-implement-staging-change)
  catalog_conflict   sql/ has the column, but the catalog says the interface does
                     not deliver it (often a stale duplicate row): one of them is
                     wrong - correct the catalog before mapping it
  planned            an approved delivery agreement promises it and the staging
                     change is not deployed yet (sql/ does not have it): the
                     developer generates it (dev-1-implement-staging-change)

A fact the request needs that is in neither the catalog nor sql/ is a gap this
tool cannot see: the analyst asks the business where it would come from.

Exit code: 0, or 1 when nothing matched / the catalog cannot be read.
"""

from __future__ import annotations

import argparse
import glob
import os
import re
import sys
from dataclasses import dataclass

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import schema_catalog  # noqa: E402

try:
    from openpyxl import load_workbook
except ImportError as exc:  # pragma: no cover - guidance path only
    raise SystemExit("openpyxl is required: pip install -r requirements.txt") from exc

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CATALOG_ENV = "UBB_SOURCE_CATALOG"
CATALOG_PATTERN = os.path.join(REPO_ROOT, "business-documents", "*Source_Systems*.xlsx")
VERSION_PATTERN = re.compile(r"_v(\d+)(?:\.(\d+))?", re.IGNORECASE)

# The catalog's column headers this tool reads (an attribute sheet has all of them).
HEADERS = {
    "system": "Source System",
    "entity": "Source Entity",
    "dataset": "Interface Dataset",
    "attribute": "Attribute / File Field",
    "business_name": "Business Attribute Name",
    "type": "Data Type (Landing / Source)",
    "meaning": "Business Meaning / Description",
    "in_interface": "In Existing Interface?",
    "notes": "BA Notes",
}
REQUIRED = ("system", "dataset", "attribute", "in_interface")

STATUSES = ("delivered", "planned", "not_staged", "interface_change", "new_interface", "catalog_conflict")
ACTION = {
    "delivered": "nothing to do",
    "planned": "in an approved delivery agreement; the staging change is generated by the developer "
               "(tools/codegen/generate_staging.py), deployed, and sql/ exported again",
    "not_staged": "delivered by the interface, not loaded into staging - fine unless a request needs it; "
                  "then the gap analysis records it as in_interface and the developer adds the staging column",
    "interface_change": "interface change: add the column to the delivery agreement and the staging table, "
                        "then to core",
    "new_interface": "new interface: delivery agreement, staging table and core columns",
    "catalog_conflict": "catalog and sql/ disagree: correct the catalog (or re-export sql/) first",
}


class CatalogError(Exception):
    pass


@dataclass
class Attribute:
    system: str
    entity: str
    dataset: str
    attribute: str
    business_name: str
    type: str
    meaning: str
    in_interface: bool
    notes: str
    sheet: str
    status: str = ""
    staging_table: str = ""  # SCHEMA.TABLE in sql/, when there is one
    listed: int = 1  # how often the catalog lists this dataset and attribute

    @property
    def action(self) -> str:
        if self.status != "catalog_conflict":
            return ACTION[self.status]
        side = "{0} has the column, but the catalog says the current interface does not deliver it".format(
            self.staging_table)
        if self.listed > 1:
            side += " (the catalog lists {0}.{1} {2} times - one row is probably stale)".format(
                self.dataset, self.attribute, self.listed)
        return "{0}; {1}".format(side, ACTION[self.status])


def _text(value) -> str:
    return " ".join(str(value).split()) if value is not None else ""


def default_catalog_path() -> str:
    """UBB_SOURCE_CATALOG, else the highest version in business-documents/."""
    if os.environ.get(CATALOG_ENV):
        return os.environ[CATALOG_ENV]
    paths = [p for p in glob.glob(CATALOG_PATTERN) if not os.path.basename(p).startswith("~$")]
    if not paths:
        raise CatalogError("no source systems catalog found ({0})".format(CATALOG_PATTERN))

    def version(path):
        match = VERSION_PATTERN.search(os.path.basename(path))
        return (int(match.group(1)), int(match.group(2) or 0)) if match else (0, 0)

    return max(paths, key=version)


def read_catalog(path: str) -> list:
    """Every attribute row of every sheet that has the attribute headers."""
    workbook = load_workbook(path, read_only=True, data_only=True)
    attributes = []
    for sheet in workbook.worksheets:
        rows = sheet.iter_rows(values_only=True)
        header = next(rows, None) or ()
        positions = {_text(cell): index for index, cell in enumerate(header)}
        columns = {key: positions.get(title) for key, title in HEADERS.items()}
        if any(columns[key] is None for key in REQUIRED):
            continue  # README, summary sheets

        def cell(row, key):
            index = columns[key]
            return _text(row[index]) if index is not None and index < len(row) else ""

        for row in rows:
            if not row or not cell(row, "attribute"):
                continue
            attributes.append(Attribute(
                system=cell(row, "system"),
                entity=cell(row, "entity"),
                dataset=cell(row, "dataset").upper(),
                attribute=cell(row, "attribute").upper(),
                business_name=cell(row, "business_name"),
                type=cell(row, "type"),
                meaning=cell(row, "meaning"),
                in_interface=cell(row, "in_interface").lower().startswith("yes"),
                notes=cell(row, "notes"),
                sheet=sheet.title,
            ))
    if not attributes:
        raise CatalogError("{0} has no sheet with the attribute headers ({1})".format(
            path, ", ".join(HEADERS[k] for k in REQUIRED)))
    return attributes


def staging_tables() -> dict:
    """{BARE_NAME: Table} for every table with a CREATE TABLE script in sql/."""
    found = {}
    for table in schema_catalog.catalog().tables.values():
        if table.has_ddl:
            found.setdefault(table.name.upper(), table)
    return found


def _entity_tables(attributes: list, tables: dict) -> dict:
    """{(system, entity): staging table name} from the rows that name one. The
    catalog writes 'Not in current interface' instead of a table for an
    attribute the interface does not carry yet; it still belongs to the
    entity's staging table when the entity has one."""
    found = {}
    for attr in attributes:
        if attr.dataset in tables:
            found.setdefault((attr.system, attr.entity), attr.dataset)
    return found


def classify(attributes: list) -> list:
    """Give every attribute its status against sql/."""
    tables = staging_tables()
    by_entity = _entity_tables(attributes, tables)
    for attr in attributes:
        if attr.dataset not in tables and (attr.system, attr.entity) in by_entity:
            attr.dataset = by_entity[(attr.system, attr.entity)]
        conventional = "STG_" + re.sub(r"\W+", "_", attr.entity.strip().upper())
        if attr.dataset not in tables and conventional in tables:
            # A delivery entity arrives in STG_<ENTITY>; a new interface's planned
            # staging table follows that convention (planned_staging.py).
            attr.dataset = conventional
        table = tables.get(attr.dataset)
        in_sql = table is not None and attr.attribute in table.columns
        attr.staging_table = table.qualified if table is not None else ""
        if in_sql and table.columns[attr.attribute].planned:
            attr.status = "planned"
        elif in_sql and attr.in_interface:
            attr.status = "delivered"
        elif in_sql:
            attr.status = "catalog_conflict"
        elif attr.in_interface:
            attr.status = "not_staged"
        elif table is not None:
            attr.status = "interface_change"
        else:
            attr.status = "new_interface"
    listed = {}
    for attr in attributes:
        listed[(attr.dataset, attr.attribute)] = listed.get((attr.dataset, attr.attribute), 0) + 1
    for attr in attributes:
        attr.listed = listed[(attr.dataset, attr.attribute)]
    return attributes


def undocumented(attributes: list, datasets: set) -> list:
    """(SCHEMA.TABLE, COLUMN) of staging columns in sql/ that the catalog does not
    list, for the given datasets (the staging tables the catalog names)."""
    tables = staging_tables()
    known = {(a.dataset, a.attribute) for a in attributes}
    result = []
    for dataset in sorted(datasets):
        table = tables.get(dataset)
        if table is None:
            continue
        result += [(table.qualified, c) for c in table.columns if (dataset, c) not in known]
    return result


def _matches(attr: Attribute, words: list) -> bool:
    text = " ".join((attr.attribute, attr.business_name, attr.meaning, attr.notes)).upper()
    return all(word.upper() in text for word in words)


def _print(attrs: list) -> None:
    for attr in attrs:
        where = attr.staging_table or "{0} (no staging table in sql/)".format(attr.dataset)
        print("{0:17} {1}.{2}  {3}".format(attr.status, where, attr.attribute, attr.type))
        print("{0:17} {1} / {2}: {3}".format("", attr.system, attr.entity, attr.meaning or attr.business_name))
        if attr.status != "delivered":
            print("{0:17} -> {1}".format("", attr.action))


def cmd_find(args, attributes: list) -> int:
    hits = [a for a in attributes if _matches(a, args.words)]
    if not hits:
        print("Nothing in the catalog matches {0}. If the request needs it, it is a gap the catalog "
              "does not know either: ask the business where it would come from.".format(" ".join(args.words)))
        return 1
    _print(hits)
    return 0


def cmd_gaps(args, attributes: list) -> int:
    wanted = {w.upper() for w in args.scope}
    scoped = [a for a in attributes if not wanted or a.dataset in wanted or a.system.upper() in wanted]
    if wanted and not scoped:
        print("No catalog attribute belongs to {0}.".format(", ".join(sorted(wanted))))
        return 1
    gaps = [a for a in scoped if a.status != "delivered"]
    counts = {s: sum(1 for a in scoped if a.status == s) for s in STATUSES}
    print("{0} attribute(s): ".format(len(scoped)) + ", ".join("{0} {1}".format(n, s) for s, n in counts.items()))
    print()
    _print(gaps)
    extra = undocumented(attributes, {a.dataset for a in scoped})
    if extra:
        print()
        print("In sql/ but not in the catalog (technical columns are expected here; a business column "
              "is a catalog_conflict):")
        for table, column in extra:
            print("  {0}.{1}".format(table, column))
    return 0


def main(argv=None) -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001
        pass
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--catalog", help="the catalog workbook (default: newest in business-documents/)")
    sub = parser.add_subparsers(dest="command", required=True)
    find = sub.add_parser("find", help="search attribute names, business names and descriptions")
    find.add_argument("words", nargs="+")
    gaps = sub.add_parser("gaps", help="attributes that are not delivered, or that sql/ disagrees on")
    gaps.add_argument("scope", nargs="*", help="interface datasets (STG_...) or source systems; none = all")
    args = parser.parse_args(argv)
    try:
        path = args.catalog or default_catalog_path()
        attributes = classify(read_catalog(path))
    except (CatalogError, OSError) as exc:
        print("ERROR: {0}".format(exc))
        return 1
    shown = os.path.abspath(path)
    if shown.lower().startswith(REPO_ROOT.lower() + os.sep):
        shown = os.path.relpath(shown, REPO_ROOT).replace(os.sep, "/")
    print("Catalog: {0}".format(shown))
    print("Compared with: the table scripts in sql/ (no database)\n")
    return cmd_find(args, attributes) if args.command == "find" else cmd_gaps(args, attributes)


if __name__ == "__main__":
    sys.exit(main())
