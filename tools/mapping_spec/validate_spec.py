"""Validate mapping workbooks, and gate edits to generated code.

Commands
--------
validate    Check every mapping workbook, specs/<folder>/<ID>.xlsx: shape,
            completeness for approved ones, and that every table and column
            it names exists in the sql/ folder. Exit 1 when any is invalid.
status      Human-readable summary of every mapping and its state.
sql-gate    Pre-edit gate for generated code, the .sql files in specs/<folder>/ (hook
            sql_gate.py, an identical copy in .claude/hooks/ for Claude Code
            and in .github/hooks/ for GitHub Copilot). Every .sql file there
            belongs to the mapping whose workbook is in the same folder, and
            may only be written while that mapping is valid and approved.
            The staging scripts of a change request, change-requests/<CR_ID>/
            staging/*.sql, are generated by tools/codegen/generate_staging.py
            and never edited by hand: every edit to them is blocked.
            Other files are ignored.

No command connects to a database.

Usage
-----
    python tools/mapping_spec/validate_spec.py validate
    python tools/mapping_spec/validate_spec.py status
    python tools/mapping_spec/validate_spec.py sql-gate specs/customer_account/PKG_X.sql
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from mapping_validation import (  # noqa: E402
    REPO_ROOT,
    SPEC_DIR,
    Report,
    load_mappings,
    validate_mapping,
)


def _rel(path: str) -> str:
    try:
        return os.path.relpath(os.path.abspath(path), REPO_ROOT).replace(os.sep, "/")
    except ValueError:
        return path.replace(os.sep, "/")


def _print_report(report: Report) -> None:
    for warning in report.warnings:
        print("  WARN  " + warning)
    for error in report.errors:
        print("  FAIL  " + error)


def _under(path: str, directory: str) -> bool:
    # normcase: on Windows "C:\x" and "c:/x" are the same file; tools differ in
    # how they spell the drive letter, and a mismatch would open the gate.
    candidate = os.path.normcase(os.path.abspath(path))
    directory = os.path.normcase(os.path.abspath(directory))
    try:
        return os.path.commonpath([candidate, directory]) == directory
    except ValueError:
        return False  # different drives on Windows - definitely not under it


def cmd_validate(args) -> int:
    mappings, report = load_mappings(SPEC_DIR)
    for mapping in mappings:
        report.merge(validate_mapping(mapping))

    print("Mapping workbooks in {0}: {1}".format(_rel(SPEC_DIR), len(mappings)))
    _print_report(report)

    if report.ok:
        approved = sum(1 for m in mappings if m.is_approved)
        print("OK: {0} mapping(s) valid, {1} approved.".format(len(mappings), approved))
        return 0
    print("")
    print("{0} problem(s) found.".format(len(report.errors)))
    return 1


def cmd_status(args) -> int:
    mappings, report = load_mappings(SPEC_DIR)
    _print_report(report)
    if not mappings:
        print("No mapping workbooks yet. Run the ba-4-create-mapping-spec skill to add one.")
        return 0

    width = max(len(m.mapping_id or "?") for m in mappings)
    print("{0}  {1:10}  {2:14}  {3}".format("MAPPING_ID".ljust(width), "STATUS", "STRATEGY", "TARGET"))
    for mapping in mappings:
        own = validate_mapping(mapping)
        flag = "" if own.ok else "  <- invalid ({0} problem(s))".format(len(own.errors))
        approval = ""
        if mapping.is_approved:
            approval = "  approved by {0} on {1}".format(mapping.get("Approved_By"), mapping.get("Approved_On"))
        print(
            "{0}  {1:10}  {2:14}  {3}{4}{5}".format(
                (mapping.mapping_id or "?").ljust(width),
                mapping.status or "?",
                mapping.load_strategy or "?",
                mapping.target or "?",
                approval,
                flag,
            )
        )
    return 0


def owning_mapping(path: str, mappings):
    """The mapping a generated .sql file belongs to, or None: the mapping
    whose workbook is in the same folder (specs/<folder>/), since generate.py
    writes all of a mapping's code next to its workbook."""
    folder = os.path.normcase(os.path.dirname(os.path.abspath(path)))
    for mapping in mappings:
        if mapping.path and os.path.normcase(os.path.dirname(os.path.abspath(mapping.path))) == folder:
            return mapping
    return None


CHANGE_REQUEST_DIR = os.path.join(REPO_ROOT, "change-requests")


def _staging_scripts(files) -> list:
    """change-requests/<CR_ID>/staging/*.sql among the touched files."""
    found = []
    for path in files:
        if not (_under(path, CHANGE_REQUEST_DIR) and path.lower().endswith(".sql")):
            continue
        parts = os.path.relpath(os.path.abspath(path), CHANGE_REQUEST_DIR).replace(os.sep, "/").split("/")
        if len(parts) == 3 and parts[1].lower() == "staging":
            found.append(path)
    return found


def cmd_sql_gate(args) -> int:
    staging = _staging_scripts(args.files)
    if staging:
        print("BLOCKED: generated staging script")
        print("")
        for path in staging:
            print("  - " + _rel(path))
        print("")
        print("These files are generated from the approved delivery agreements of the change request and")
        print("are never edited by hand. Change the agreement (/ba-3-specify-baseline-changes), have it")
        print("approved, then regenerate: python tools/codegen/generate_staging.py <CR_ID>")
        return 1
    touched = [p for p in args.files if _under(p, SPEC_DIR) and p.lower().endswith(".sql")]
    if not touched:
        return 0

    mappings, _load_report = load_mappings(SPEC_DIR)
    problems = []
    for path in touched:
        mapping = owning_mapping(path, mappings)
        if mapping is None:
            problems.append(
                "{0} is not in a mapping folder - generated code only exists next to "
                "its mapping workbook, specs/<folder>/<MAPPING_ID>.xlsx".format(_rel(path))
            )
            continue
        own = validate_mapping(mapping)
        if not mapping.is_approved:
            problems.append(
                "{0} belongs to {1}, which is '{2}', not approved".format(
                    _rel(path), mapping.mapping_id, mapping.status or "?"
                )
            )
        elif not own.ok:
            problems.append(
                "{0} belongs to {1}, which is approved but invalid: {2}".format(
                    _rel(path), mapping.mapping_id, own.errors[0]
                )
            )
    if not problems:
        return 0

    print("BLOCKED: generated-code gate")
    print("")
    print("SQL in a mapping folder (specs/<folder>/) is generated from that folder's workbook")
    print("and may only change while that mapping is approved:")
    for problem in problems:
        print("  - " + problem)
    print("")
    print("Finish the mapping first (ba-4-create-mapping-spec), have a named person approve it,")
    print("then generate the code (dev-2-implement-mapping). Check with:")
    print("  python tools/mapping_spec/validate_spec.py status")
    return 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("validate", help="check every mapping workbook")
    sub.add_parser("status", help="summarise all mapping workbooks")
    sql_gate = sub.add_parser("sql-gate", help="block edits to generated code of an unapproved mapping")
    sql_gate.add_argument("files", nargs="*")

    args = parser.parse_args(argv)
    handlers = {
        "validate": cmd_validate,
        "status": cmd_status,
        "sql-gate": cmd_sql_gate,
    }
    return handlers[args.command](args)


if __name__ == "__main__":
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:  # noqa: BLE001 - redirected or older streams
        pass
    sys.exit(main())
